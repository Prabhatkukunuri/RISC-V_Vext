"""Edge-case verification of the vector-addition and dot-product programs.

The code of benchmarks/programs/{vadd,dot}_{scalar,vector}.s is reused unchanged; only the
element count (`li a3, N`) and the input arrays are replaced. Every generated program is run on
Kites and checked against a Python reference:

  * the result in `out` must match exactly (32-bit wrap-around arithmetic);
  * a 64-byte guard area after `out` must still be zero (no store past the last element);
  * on the single-cycle VM the dynamic instruction count must equal the analytic model, and the
    number of vector elements processed must equal the expected work.

Case groups: element counts around multiples of VLMAX, data patterns (zeros, -1, int32
extremes / overflow), VLEN 128-1024, and the pipelined VMs with hazard detection.

Writes benchmarks/results/edge_cases.json, the LaTeX tables in docs/verification/tables/ and the
figure docs/verification/speedup_vs_n.{pdf,png}.

usage: python benchmarks/edge_cases.py [--cli PATH]
"""
import argparse
import json
import math
import os
import random
import re
import shutil
import subprocess
import sys
import tempfile

import run_benchmarks as rb

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
DOC = os.path.join(REPO, "docs", "verification")
GUARD = 64  # bytes after `out` that must stay zero
INT_MAX, INT_MIN = 2**31 - 1, -2**31


def wrap(v):
    return ((v + 2**31) % 2**32) - 2**31


# kernel -> reference, out size in bytes, model(N, VLMAX) for scalar / vector
KERNELS = {
    "vadd": dict(title="Vector addition", ref=lambda a, b: [wrap(p + q) for p, q in zip(a, b)],
                 out_bytes=lambda n: 4 * n,
                 scalar=lambda n: 7 + 9 * n,
                 vector=lambda n, vlmax: 7 + 11 * max(1, math.ceil(n / vlmax)),
                 elements=lambda n: 4 * n, small=100000),
    "dot": dict(title="Dot product", ref=lambda a, b: [wrap(sum(p * q for p, q in zip(a, b)))],
                out_bytes=lambda n: 4,
                scalar=lambda n: 9 + 8 * n,
                vector=lambda n, vlmax: 11 + 10 * max(1, math.ceil(n / vlmax)),
                elements=lambda n: 4 * n + 2, small=100),
}


def code_of(kernel, variant):
    """The .text section of the original program (instructions and comments)."""
    src = open(os.path.join(rb.PROGRAMS, f"{kernel}_{variant}.s")).read()
    text = src[src.index("        .text"):src.index("        .data")]
    assert re.search(r"li\s+a3,\s*256", text)
    return text


def words(label, values):
    if not values:
        return f"{label}:  .word 0                    # unused (N = 0)\n"
    lines = [f"{label}:"]
    for i in range(0, len(values), 16):
        lines.append(("        " if i else "  ") + ".word " + ", ".join(map(str, values[i:i + 16])))
    return "\n".join(lines) + "\n"


def make_program(kernel, variant, n, a, b, note):
    text = re.sub(r"li\s+a3,\s*256", f"li      a3, {n}", code_of(kernel, variant))
    out = KERNELS[kernel]["out_bytes"](n) + GUARD
    return (f"# generated by benchmarks/edge_cases.py from {kernel}_{variant}.s: N = {n}, {note}\n"
            + text + "        .data\n" + f"out:    .zero   {out}\n" + words("a", a) + words("b", b))


def run(cli, env, kernel, variant, n, a, b, note, vlen=128, vm="rvss"):
    k = KERNELS[kernel]
    expected = rb.i32(k["ref"](a, b))
    work = tempfile.mkdtemp(prefix="kites_edge_")
    try:
        asm = os.path.join(work, "prog.s")
        open(asm, "w").write(make_program(kernel, variant, n, a, b, note))
        rows = math.ceil((len(expected) + GUARD) / 8)
        cmd = [cli, asm, "--vm", vm, "--vlen", str(vlen), "--mem-dump", "0x10000000", str(rows)]
        if vm == "rvss":
            cmd.append("--stats")
        proc = subprocess.run(cmd, cwd=work, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                              timeout=900, env=env)
        state = os.path.join(work, "vm_state")

        def load(name):
            p = os.path.join(state, name)
            return json.load(open(p)) if os.path.exists(p) else None

        errors = (load("errors_dump.json") or {}).get("errors", ["no errors_dump.json"])
        memory = load("memory_dump.json") or {}
        out = bytearray()
        for row in sorted(memory, key=lambda x: int(x, 16)):
            out += int(memory[row], 16).to_bytes(8, "little")
        r = dict(kernel=kernel, variant=variant, n=n, note=note, vlen=vlen, vm=vm,
                 result_ok=proc.returncode == 0 and not errors
                 and bytes(out[:len(expected)]) == expected,
                 guard_ok=bytes(out[len(expected):len(expected) + GUARD]) == bytes(GUARD))
        stats = load("stats_dump.json") if vm == "rvss" else None
        if stats:
            vlmax = 8 * vlen // 32
            r["metrics"] = rb.metrics(stats, max(n, 1))
            r["instructions"] = stats["instructions_retired"]
            r["model"] = (k["scalar"](n) if variant == "scalar" else k["vector"](n, vlmax))
            r["model_ok"] = r["instructions"] == r["model"]
            if variant == "vector":
                r["elements"] = stats["vector"]["elements"]
                r["elements_ok"] = r["elements"] == k["elements"](n)
                r["vlmax"] = vlmax
                r["passes"] = max(1, math.ceil(n / vlmax))
                r["last_vl"] = n - (r["passes"] - 1) * vlmax
        r["ok"] = r["result_ok"] and r["guard_ok"] and r.get("model_ok", True) \
            and r.get("elements_ok", True)
        return r
    finally:
        shutil.rmtree(work, ignore_errors=True)


def data(kernel, n, pattern, rng):
    lim = KERNELS[kernel]["small"]
    if pattern == "random":
        return [rng.randint(-lim, lim) for _ in range(n)], [rng.randint(-lim, lim) for _ in range(n)]
    if pattern == "zeros":
        return [0] * n, [0] * n
    if pattern == "minus_one":
        return [-1] * n, [-1] * n
    if pattern == "extremes":  # INT32_MAX + 1, INT32_MIN - 1, ... -> 32-bit wrap-around
        cyc_a, cyc_b = [INT_MAX, INT_MIN, INT_MAX, -1, 0], [1, -1, INT_MAX, INT_MIN, INT_MIN]
        return [cyc_a[i % 5] for i in range(n)], [cyc_b[i % 5] for i in range(n)]
    if pattern == "full_range":
        return ([rng.randint(INT_MIN, INT_MAX) for _ in range(n)],
                [rng.randint(INT_MIN, INT_MAX) for _ in range(n)])
    raise ValueError(pattern)


PATTERNS = [
    ("zeros", 256, "all inputs 0"),
    ("minus_one", 256, "all inputs -1 (sign extension)"),
    ("extremes", 37, "operands INT32_MAX, INT32_MIN, -1, 0: most results overflow 32 bits"),
    ("full_range", 256, "random values over the whole int32 range"),
]
LENGTHS = [1, 2, 7, 31, 32, 33, 64, 100, 255, 256, 257, 1000, 4096]
VLENS = [128, 256, 512, 1024]
VLEN_NS = [33, 256, 1000]
PIPE_VMS = ["rv5-h-nf", "rv5-h-f"]
PIPE_NS = [1, 33, 256]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cli", default=rb.find_cli())
    args = ap.parse_args()
    if not args.cli or not os.path.exists(args.cli):
        sys.exit("kites-cli not found; build it or pass --cli")
    cli = os.path.abspath(args.cli)
    env = dict(os.environ)
    if os.name == "nt" and os.path.isdir(r"C:\msys64\ucrt64\bin"):
        env["PATH"] = r"C:\msys64\ucrt64\bin" + os.pathsep + env.get("PATH", "")

    results = []

    def go(*a, **kw):
        r = run(cli, env, *a, **kw)
        results.append(r)
        print(f"  {'ok' if r['ok'] else 'FAIL':4} {r['kernel']:5} {r['variant']:6} N={r['n']:<5} "
              f"VLEN={r['vlen']:<5} {r['vm']:9} {r['note']}"
              + (f"  IC={r['instructions']}" if 'instructions' in r else ""))
        return r

    for kernel in KERNELS:
        print(f"{kernel}: element counts")
        for n in LENGTHS:
            rng = random.Random(1000 + n)
            a, b = data(kernel, n, "random", rng)
            for variant in ("scalar", "vector"):
                go(kernel, variant, n, a, b, "random")
        go(kernel, "vector", 0, [], [], "empty input")  # the scalar loop requires N >= 1
        print(f"{kernel}: data patterns")
        for pattern, n, note in PATTERNS:
            a, b = data(kernel, n, pattern, random.Random(7))
            for variant in ("scalar", "vector"):
                go(kernel, variant, n, a, b, pattern)
        print(f"{kernel}: VLEN")
        for n in VLEN_NS:
            a, b = data(kernel, n, "random", random.Random(1000 + n))
            for vlen in VLENS[1:]:
                go(kernel, "vector", n, a, b, "random", vlen=vlen)
            go(kernel, "scalar", n, a, b, "random", vlen=1024)
        print(f"{kernel}: pipelined VMs")
        for vm in PIPE_VMS:
            for n in PIPE_NS:
                a, b = data(kernel, n, "random", random.Random(1000 + n))
                for variant in ("scalar", "vector"):
                    go(kernel, variant, n, a, b, "random", vm=vm)

    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    json.dump(results, open(os.path.join(HERE, "results", "edge_cases.json"), "w"), indent=1)
    write_tables(results)
    write_figure(results)
    bad = [r for r in results if not r["ok"]]
    print(f"\n{len(results)} runs, {len(results) - len(bad)} passed, {len(bad)} failed")
    if bad:
        sys.exit(1)


# ------------------------------------------------------------------------------- LaTeX output
def find(results, **kw):
    return [r for r in results if all(r.get(k) == v for k, v in kw.items())]


def one(results, **kw):
    m = find(results, **kw)
    assert len(m) == 1, (kw, len(m))
    return m[0]


def mark(ok):
    return r"\cmark" if ok else r"\xmark"


def n_fmt(v):
    return f"{v:,}".replace(",", "{,}")


def write_tables(results):
    os.makedirs(os.path.join(DOC, "tables"), exist_ok=True)

    def save(name, lines):
        with open(os.path.join(DOC, "tables", name), "w", newline="\n") as f:
            f.write("% generated by benchmarks/edge_cases.py -- do not edit\n" + "\n".join(lines)
                    + "\n")

    # length sweep, one table per kernel
    for kernel in KERNELS:
        rows = []
        for n in [0] + LENGTHS:
            v = one(results, kernel=kernel, variant="vector", n=n, vlen=128, vm="rvss",
                    note="empty input" if n == 0 else "random")
            s = find(results, kernel=kernel, variant="scalar", n=n, vlen=128, vm="rvss",
                     note="random")
            s = s[0] if s else None
            speed = f"{s['instructions'] / v['instructions']:.2f}" if s else "--"
            rows.append(" & ".join([
                n_fmt(n), str(v["passes"]), str(v["last_vl"] if n else 0),
                f"{n_fmt(s['instructions'])} ({n_fmt(s['model'])})" if s else r"\emph{not run}",
                f"{n_fmt(v['instructions'])} ({n_fmt(v['model'])})", speed,
                n_fmt(v["elements"]),
                mark(v["ok"] and (s is None or s["ok"]))]) + r" \\")
        save(f"length_{kernel}.tex", rows)

    # data patterns
    rows = []
    for kernel in KERNELS:
        for pattern, n, note in PATTERNS:
            s = one(results, kernel=kernel, variant="scalar", note=pattern)
            v = one(results, kernel=kernel, variant="vector", note=pattern)
            rows.append(" & ".join([KERNELS[kernel]["title"], pattern.replace("_", r"\_"),
                                    str(n), note.replace("_", r"\_").replace("-1", "$-1$"),
                                    mark(s["ok"]), mark(v["ok"])]) + r" \\")
    save("patterns.tex", rows)

    # VLEN sweep
    rows = []
    for kernel in KERNELS:
        for n in VLEN_NS:
            s = one(results, kernel=kernel, variant="scalar", n=n, vlen=1024, vm="rvss")
            for vlen in VLENS:
                v = one(results, kernel=kernel, variant="vector", n=n, vlen=vlen, vm="rvss",
                        note="random")
                rows.append(" & ".join([KERNELS[kernel]["title"], n_fmt(n), str(vlen),
                                        str(v["vlmax"]), str(v["passes"]),
                                        f"{n_fmt(v['instructions'])} ({n_fmt(v['model'])})",
                                        n_fmt(s["instructions"]),
                                        f"{s['instructions'] / v['instructions']:.1f}",
                                        mark(v["ok"] and s["ok"])]) + r" \\")
            rows.append(r"\addlinespace[2pt]")
    save("vlen.tex", rows[:-1])

    # pipelined VMs
    rows = []
    for vm in PIPE_VMS:
        for kernel in KERNELS:
            cells = []
            for n in PIPE_NS:
                s = one(results, kernel=kernel, variant="scalar", n=n, vm=vm)
                v = one(results, kernel=kernel, variant="vector", n=n, vm=vm)
                cells += [mark(s["ok"]), mark(v["ok"])]
            rows.append(" & ".join([f"\\texttt{{{vm}}}", KERNELS[kernel]["title"]] + cells)
                        + r" \\")
    save("pipelines.tex", rows)

    # instruction mix and memory statistics at N = 256 and N = 4096
    rows = []
    for kernel in KERNELS:
        for n in (256, 4096):
            for variant in ("scalar", "vector"):
                m = one(results, kernel=kernel, variant=variant, n=n, vlen=128, vm="rvss",
                        note="random")["metrics"]
                rows.append(" & ".join([
                    f"{KERNELS[kernel]['title']}, $N={n_fmt(n)}$" if variant == "scalar" else "",
                    variant, n_fmt(m["alu"]), n_fmt(m["load_store"]), n_fmt(m["branch_jump"]),
                    n_fmt(m["vector_config"]), n_fmt(m["vector_load_store"]),
                    n_fmt(m["vector_compute"]), n_fmt(m["instructions"]),
                    f"{m['instructions_per_element']:.3f}"]) + r" \\")
            rows.append(r"\midrule")
    save("mix.tex", rows[:-1])

    rows = []
    for kernel in KERNELS:
        for n in (256, 4096):
            s = one(results, kernel=kernel, variant="scalar", n=n, vlen=128, vm="rvss",
                    note="random")["metrics"]
            v = one(results, kernel=kernel, variant="vector", n=n, vlen=128, vm="rvss",
                    note="random")["metrics"]
            rows.append(" & ".join([
                KERNELS[kernel]["title"], n_fmt(n),
                f"{n_fmt(s['memory_instructions'])} / {n_fmt(v['memory_instructions'])}",
                f"{s['memory_instructions'] / v['memory_instructions']:.1f}",
                f"{n_fmt(s['bytes_moved'])} / {n_fmt(v['bytes_moved'])}",
                f"{n_fmt(s['branches'])} / {n_fmt(v['branches'])}",
                f"{v['elements_per_vector_instruction']:.1f}",
                f"{s['instructions'] / v['instructions']:.1f}"]) + r" \\")
    save("memory.tex", rows)

    total = len(results)
    passed = sum(r["ok"] for r in results)
    save("summary.tex", [f"\\newcommand{{\\runsTotal}}{{{total}}}",
                         f"\\newcommand{{\\runsPassed}}{{{passed}}}"])


def write_figure(results):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("figure skipped (matplotlib missing)")
        return
    colors = {"vadd": "#2a78d6", "dot": "#eb6834"}
    limits = {"vadd": 9 * 32 / 11, "dot": 8 * 32 / 10}
    fig, ax = plt.subplots(figsize=(7.2, 3.9))
    for kernel in KERNELS:
        ns, sp = [], []
        for n in LENGTHS:
            s = one(results, kernel=kernel, variant="scalar", n=n, vlen=128, vm="rvss",
                    note="random")
            v = one(results, kernel=kernel, variant="vector", n=n, vlen=128, vm="rvss",
                    note="random")
            ns.append(n)
            sp.append(s["instructions"] / v["instructions"])
        k = KERNELS[kernel]
        grid = list(range(1, 4097))
        ax.plot(grid, [k["scalar"](g) / k["vector"](g, 32) for g in grid], color=colors[kernel],
                lw=1.0, alpha=0.45)
        ax.plot(ns, sp, "o", color=colors[kernel], ms=5.5, mec="white", mew=1.2,
                label=f"{k['title']} (measured; line = model)")
        ax.axhline(limits[kernel], color=colors[kernel], lw=0.9, ls=(0, (4, 3)))
        ax.text(4600, limits[kernel] + (0.55 if kernel == "vadd" else -0.55),
                f"limit {limits[kernel]:.1f}x", color="#45443f", fontsize=8, va="center")
    ax.axhline(1, color="#898781", lw=0.8)
    ax.text(1.05, 1.15, "break-even (1x)", fontsize=8, color="#45443f", va="bottom")
    ax.set_xscale("log", base=2)
    ax.set_xlim(0.8, 4096 * 3.2)
    ax.set_ylim(0, 29)
    ax.set_xticks([1, 4, 16, 32, 64, 256, 1024, 4096])
    ax.set_xticklabels(["1", "4", "16", "32", "64", "256", "1024", "4096"])
    ax.set_xlabel("Number of elements N (log scale)")
    ax.set_ylabel("Speedup = IC scalar / IC vector")
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    ax.grid(axis="y", color="#e1e0d9", lw=0.8)
    ax.set_axisbelow(True)
    ax.legend(frameon=False, loc="lower right", fontsize=8.5)
    fig.tight_layout()
    for ext in ("pdf", "png"):
        fig.savefig(os.path.join(DOC, f"speedup_vs_n.{ext}"), dpi=200)
    plt.close(fig)


if __name__ == "__main__":
    main()
