# ============================================================================================
#  AXPY (out = a * x + y) -- VECTOR version (RVV 1.0)
# ============================================================================================
#  C equivalent:
#      int32_t x[256], y[256], out[256];
#      for (int i = 0; i < 256; i++)
#          out[i] = 3 * x[i] + y[i];         // AXPY with a = 3
#
#  Strip-mining: each pass, vsetvli sets vl = min(elements left, VLMAX). With 32-bit
#  elements (e32), register groups of 8 (m8) and VLEN = 128 bits, VLMAX = 8 * 128 / 32 = 32,
#  so the 256 elements take 8 passes. The same code runs unchanged on a machine with a
#  longer VLEN; it just needs fewer passes.
#  vmacc.vx does the multiply and the add in one instruction: vd += rs1 * vs2.
#
#  Registers:
#      a0  &x[i]          a1  &y[i]          a2  &out[i]        a3  elements left
#      s0  a = 3          t0  vl             t1  vl * 4 (bytes this pass)
#      v0-v7    x[i .. i+vl-1]   v8-v15   y[i .. i+vl-1], then the result
#
#  Instructions executed (dynamic count):
#      setup  8   (3 x la = 6, 2 x li = 2)
#      loop   11 instructions x 8 passes = 88
#      total  96
#
#  Result in `out` (0x10000000):
#      out[0..3] = #,  ,  ,  
#
#  Run:  kites-cli benchmarks/programs/saxpy_vector.s --stats --mem-dump 0x10000000 128
# ============================================================================================

        .text
        la      a0, x                   # a0 = &x[0]
        la      a1, y                   # a1 = &y[0]
        la      a2, out                 # a2 = &out[0]
        li      a3, 256                 # a3 = number of elements
        li      s0, 3                   # s0 = a
loop:
        vsetvli t0, a3, e32, m8, ta, ma # t0 = vl = min(a3, VLMAX)
        vle32.v v0, (a0)                # v0-v7  = x[i .. i+vl-1]
        vle32.v v8, (a1)                # v8-v15 = y[i .. i+vl-1]
        vmacc.vx v8, s0, v0             # v8-v15 += a * x   (multiply-add, vl elements)
        vse32.v v8, (a2)                # out[i .. i+vl-1] = v8-v15
        slli    t1, t0, 2               # t1 = bytes processed = vl * 4
        add     a0, a0, t1              # advance the three pointers by vl elements
        add     a1, a1, t1
        add     a2, a2, t1
        sub     a3, a3, t0              # vl elements done
        bnez    a3, loop                # repeat while elements are left

        .data
out:    .zero   1024                    # out[256] (written by the program)

