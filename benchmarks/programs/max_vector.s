# ============================================================================================
#  Array maximum -- VECTOR version (RVV 1.0)
# ============================================================================================
#  C equivalent:
#      int32_t a[256];
#      int32_t m = a[0];
#      for (int i = 1; i < 256; i++)
#          if (a[i] > m) m = a[i];
#      out = m;
#
#  Strip-mining: each pass, vsetvli sets vl = min(elements left, VLMAX). With 32-bit
#  elements (e32), register groups of 8 (m8) and VLEN = 128 bits, VLMAX = 8 * 128 / 32 = 32,
#  so the 256 elements take 8 passes. The same code runs unchanged on a machine with a
#  longer VLEN; it just needs fewer passes.
#  vredmax.vs takes the maximum of vl elements and v24[0] in one instruction, so there
#  is no compare-and-branch per element.
#
#  Registers:
#      a0  &a[i]          a2  &out           a3  elements left  a4  the final maximum
#      t0  vl             t1  vl * 4 (bytes this pass)          t2  INT32_MIN
#      v0-v7  a[i .. i+vl-1]                 v24[0]  running maximum
#
#  Instructions executed (dynamic count):
#      setup  8   (2 x la = 4, 2 x li, vsetvli, vmv.s.x)
#      loop   7 instructions x 8 passes = 56
#      end    2   (vmv.x.s, sw)
#      total  66
#
#  Result in `out` (0x10000000):
#      out = 991871
#
#  Run:  kites-cli benchmarks/programs/max_vector.s --stats --mem-dump 0x10000000 1
# ============================================================================================

        .text
        la      a0, a                   # a0 = &a[0]
        la      a2, out                 # a2 = &out
        li      a3, 256                 # a3 = number of elements
        li      t2, -2147483648         # t2 = INT32_MIN
        vsetvli t0, x0, e32, m1, ta, ma # any vl > 0, so that vmv.s.x writes element 0
        vmv.s.x v24, t2                 # v24[0] = max = INT32_MIN
loop:
        vsetvli t0, a3, e32, m8, ta, ma # t0 = vl = min(a3, VLMAX)
        vle32.v v0, (a0)                # v0-v7 = a[i .. i+vl-1]
        vredmax.vs v24, v0, v24         # v24[0] = max(v24[0], a[i .. i+vl-1])
        slli    t1, t0, 2               # t1 = bytes processed = vl * 4
        add     a0, a0, t1              # advance the pointer by vl elements
        sub     a3, a3, t0              # vl elements done
        bnez    a3, loop                # repeat while elements are left
        vmv.x.s a4, v24                 # a4 = v24[0] = max
        sw      a4, 0(a2)               # out = max

        .data
out:    .zero   4                       # the maximum (written by the program)

