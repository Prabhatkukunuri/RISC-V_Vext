        li      a4, 32
        li      a5, 10
        li      a6, 0                   # no ReLU on the output layer
        jal     ra, dense
# ---- argmax:  cls = index of the largest logit (the first one on a tie) ----------------------
        la      t1, logits              # t1 = &logits[0]
        lw      t2, 0(t1)               # t2 = best = logits[0]
        li      t3, 0                   # t3 = cls  = 0
        li      t4, 1                   # t4 = k    = 1
        li      t5, 10                  # t5 = number of logits
aloop:
        addi    t1, t1, 4               # t1 = &logits[k]
        lw      t6, 0(t1)               # t6 = logits[k]
        ble     t6, t2, anext           # not larger: keep the current best
        mv      t2, t6                  # best = logits[k]
        mv      t3, t4                  # cls  = k
anext:
        addi    t4, t4, 1               # k++
        blt     t4, t5, aloop
        la      t1, cls
        sw      t3, 0(t1)               # store the predicted digit
        j       end

# ---- dense(x=a0, W=a1, b=a2, y=a3, n_in=a4, n_out=a5, relu=a6) --------------------------------
#      one neuron per iteration of jloop; one multiply-accumulate per iteration of iloop
dense:
        slli    t3, a5, 2               # t3 = n_out * 4 = bytes per row of W
jloop:
        lw      t0, 0(a2)               # t0 = acc = b[j]
        mv      t1, a0                  # t1 = &x[0]
        mv      t2, a1                  # t2 = &W[0][j]
        mv      t4, a4                  # t4 = inputs left
iloop:
        lw      t5, 0(t1)               # t5 = x[i]
        lw      t6, 0(t2)               # t6 = W[i][j]
        mulw    t5, t5, t6              # t5 = x[i] * W[i][j]   (32-bit)
        addw    t0, t0, t5              # acc += x[i] * W[i][j] (32-bit)
        addi    t1, t1, 4               # next input
        add     t2, t2, t3              # next row of W, same column j
        addi    t4, t4, -1
        bnez    t4, iloop
        beqz    a6, store
        slti    t5, t0, 0               # ReLU without a branch: t5 = (acc < 0)
        addi    t5, t5, -1              #   t5 = acc < 0 ? 0 : all ones
        and     t0, t0, t5              #   acc = max(acc, 0)
        srai    t0, t0, 7               # rescale: acc >>= 7
store:
        sw      t0, 0(a3)               # y[j] = acc
        addi    a1, a1, 4               # next column of W
        addi    a2, a2, 4               # next bias
        addi    a3, a3, 4               # next output
        addi    a5, a5, -1              # one neuron done
        bnez    a5, jloop
        ret
end:

