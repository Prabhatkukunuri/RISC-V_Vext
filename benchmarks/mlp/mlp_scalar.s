#  MLP inference (64-32-10 handwritten-digit classifier) -- SCALAR version (RV64IM)
# ============================================================================================
#  One inference with fixed, pre-trained weights. Self-contained: the weights, the biases and
#  the input image are in the .data section (the same values as in mlp_weights.h).
#
#  C equivalent (mlp.c):
#      dense(input, W1, b1, hidden, 64, 32, 1, 7);   // layer 1: 64 -> 32, ReLU, >> 7
#      dense(hidden, W2, b2, logits, 32, 10, 0, 0);  // layer 2: 32 -> 10
#      cls = argmax(logits, 10);                     // first maximum on a tie
#  where dense() computes y[j] = b[j] + sum_i x[i] * W[i][j] (then max(y, 0) >> 7 if relu).
#
#  Result: cls = 2 (the input image is a handwritten 2).
#      cls at 0x10000000, logits[0..9] at 0x10000004, hidden[0..31] at 0x1000002c
#
#  Run:  kites-cli benchmarks/mlp/mlp_scalar.s --stats --mem-dump 0x10000000 22
# ============================================================================================

        .text
# ---- layer 1:  hidden = max(input . W1 + b1, 0) >> 7 ----------------------------------------
        la      a0, input               # a0 = x        (64 pixels)
        la      a1, W1                  # a1 = W        (64 x 32, row i = weights from input i)
        la      a2, b1                  # a2 = b        (32 biases)
        la      a3, hidden              # a3 = y        (32 outputs)
        li      a4, 64                  # a4 = n_in
        li      a5, 32                  # a5 = n_out
        li      a6, 1                   # a6 = relu
